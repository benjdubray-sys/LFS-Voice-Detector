def _parse(raw):
    out = {}
    for line in raw.strip().splitlines():
        if "=" in line:
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip()
    return out


STRINGS = {code: _parse(raw) for code, raw in _RAW.items()}
EN = STRINGS["en"]


def tr(lang, name, /, **kw):
    s = STRINGS.get(lang, {}).get(name) or EN.get(name) or name
    try:
        return s.format(**kw) if kw else s
    except (KeyError, IndexError):
        return s


def default_language(locale_name):
    """Choisit la langue d'interface depuis un nom de locale ('fr_FR', 'de-DE'…)."""
    code = (locale_name or "").replace("-", "_").split("_")[0].lower()
    return code if code in STRINGS else "en"
